-- Notifications persistence for the AQ Setu client portal.
-- Safe to apply more than once.
create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  client_id text,
  recipient_role text not null check (recipient_role in ('admin', 'client')),
  event_key text not null,
  title text not null,
  message text not null default '',
  target_url text,
  is_read boolean not null default false,
  created_at timestamptz not null default now()
);

-- Existing deployments may already have the table but be missing newer columns.
alter table public.notifications
  add column if not exists client_id text,
  add column if not exists recipient_role text,
  add column if not exists event_key text,
  add column if not exists title text,
  add column if not exists message text default '',
  add column if not exists target_url text,
  add column if not exists is_read boolean not null default false,
  add column if not exists created_at timestamptz not null default now();

-- Existing rows from older schemas need stable values before enforcing constraints.
update public.notifications
set recipient_role = coalesce(nullif(recipient_role, ''), 'admin'),
    event_key = coalesce(nullif(event_key, ''), 'legacy:' || id::text),
    title = coalesce(nullif(title, ''), 'Notification'),
    message = coalesce(message, ''),
    created_at = coalesce(created_at, now())
where recipient_role is null
   or event_key is null
   or title is null
   or message is null
   or created_at is null;

create unique index if not exists notifications_recipient_client_event_key
  on public.notifications (recipient_role, client_id, event_key);

create index if not exists notifications_recipient_created_at
  on public.notifications (recipient_role, created_at desc);

create index if not exists notifications_client_created_at
  on public.notifications (client_id, created_at desc);

alter table public.notifications enable row level security;

